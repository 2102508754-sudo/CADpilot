"""CADPilot Agent State Schema.

Defines the centralized agent state for the LangGraph state machine,
including the natural language specification schema (TaskSpec), geometric
feasibility reports, CAD sequence execution plans, execution observations,
and closed-loop reflection state.
"""

from typing import TypedDict, Dict, Any, List, Optional, Union
from dataclasses import dataclass, field, asdict
import json


@dataclass
class HoleSpec:
    """Specification for a circular hole feature."""
    position: List[float]  # [x, y] in mm
    diameter: float  # mm
    depth: Union[float, str] = "through"  # mm or "through"
    face: str = "xy"
    description: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "HoleSpec":
        return cls(
            position=[float(data["position"][0]), float(data["position"][1])],
            diameter=float(data["diameter"]),
            depth=float(data["depth"]) if isinstance(data.get("depth"), (int, float)) else data.get("depth", "through"),
            face=data.get("face", "xy"),
            description=data.get("description", "")
        )


@dataclass
class FilletSpec:
    """Specification for edge fillet features."""
    radius: float  # mm
    target: str = "all_vertical_edges"  # Edge token, list of tokens, or "all_vertical_edges"
    description: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "FilletSpec":
        return cls(
            radius=float(data["radius"]),
            target=data.get("target", "all_vertical_edges"),
            description=data.get("description", "")
        )


@dataclass
class ExportSpec:
    """Specification for CAD artifact export."""
    format: str = "step"  # "step", "stl", "f3d"
    output_path: str = "/tmp/cadpilot_output.step"

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "ExportSpec":
        return cls(
            format=data.get("format", "step"),
            output_path=data.get("output_path", "/tmp/cadpilot_output.step")
        )


@dataclass
class TaskSpec:
    """Structured geometric and mechanical design specification."""
    part_type: str = "mounting_plate"  # "mounting_plate", "l_bracket", "standoff", "custom"
    base_plane: str = "xy"
    shape_type: str = "rectangle"  # "rectangle", "circle"
    dimensions: Dict[str, float] = field(default_factory=lambda: {"width": 42.3, "height": 42.3, "thickness": 4.0})
    center: List[float] = field(default_factory=lambda: [0.0, 0.0])
    holes: List[HoleSpec] = field(default_factory=list)
    fillets: Optional[FilletSpec] = None
    export: Optional[ExportSpec] = None
    raw_prompt: str = ""

    def to_dict(self) -> Dict[str, Any]:
        res = asdict(self)
        res["holes"] = [h.to_dict() for h in self.holes]
        if self.fillets:
            res["fillets"] = self.fillets.to_dict()
        if self.export:
            res["export"] = self.export.to_dict()
        return res

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "TaskSpec":
        holes = [HoleSpec.from_dict(h) for h in data.get("holes", [])]
        fillets = FilletSpec.from_dict(data["fillets"]) if data.get("fillets") else None
        export = ExportSpec.from_dict(data["export"]) if data.get("export") else None
        return cls(
            part_type=data.get("part_type", "mounting_plate"),
            base_plane=data.get("base_plane", "xy"),
            shape_type=data.get("shape_type", "rectangle"),
            dimensions={k: float(v) for k, v in data.get("dimensions", {}).items()},
            center=[float(c) for c in data.get("center", [0.0, 0.0])],
            holes=holes,
            fillets=fillets,
            export=export,
            raw_prompt=data.get("raw_prompt", "")
        )


@dataclass
class FeasibilityReport:
    """Report generated by pre-flight geometric feasibility check."""
    is_feasible: bool = True
    errors: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    remediation_hints: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "FeasibilityReport":
        return cls(
            is_feasible=bool(data.get("is_feasible", True)),
            errors=list(data.get("errors", [])),
            warnings=list(data.get("warnings", [])),
            remediation_hints=list(data.get("remediation_hints", []))
        )


@dataclass
class PlanStep:
    """A discrete tool call step in the ordered CAD generation plan."""
    step_index: int
    tool: str  # JSON-RPC method name
    params: Dict[str, Any]
    description: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "PlanStep":
        return cls(
            step_index=int(data["step_index"]),
            tool=str(data["tool"]),
            params=dict(data.get("params", {})),
            description=str(data.get("description", ""))
        )


@dataclass
class CADPlan:
    """Ordered sequence of CAD tool operations to produce the part."""
    steps: List[PlanStep] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {"steps": [s.to_dict() for s in self.steps]}

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "CADPlan":
        return cls(steps=[PlanStep.from_dict(s) for s in data.get("steps", [])])


@dataclass
class ExecutionObservation:
    """Observation recorded after executing a CAD tool call."""
    step_index: int
    tool: str
    status: str  # "success" or "error"
    result: Optional[Dict[str, Any]] = None
    error_code: Optional[int] = None
    error_message: Optional[str] = None
    error_hint: Optional[str] = None
    bounding_box: Optional[Dict[str, Any]] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "ExecutionObservation":
        return cls(
            step_index=int(data["step_index"]),
            tool=str(data["tool"]),
            status=str(data["status"]),
            result=data.get("result"),
            error_code=data.get("error_code"),
            error_message=data.get("error_message"),
            error_hint=data.get("error_hint"),
            bounding_box=data.get("bounding_box")
        )


@dataclass
class ReflectionState:
    """Maintains error state and retry tracking for closed-loop self-correction."""
    retry_count: int = 0
    max_retries: int = 3
    last_error_tool: Optional[str] = None
    last_error_code: Optional[int] = None
    last_error_message: Optional[str] = None
    last_error_hint: Optional[str] = None
    history: List[Dict[str, Any]] = field(default_factory=list)
    resolved: bool = False

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "ReflectionState":
        return cls(
            retry_count=int(data.get("retry_count", 0)),
            max_retries=int(data.get("max_retries", 3)),
            last_error_tool=data.get("last_error_tool"),
            last_error_code=data.get("last_error_code"),
            last_error_message=data.get("last_error_message"),
            last_error_hint=data.get("last_error_hint"),
            history=list(data.get("history", [])),
            resolved=bool(data.get("resolved", False))
        )


class CADState(TypedDict, total=False):
    """LangGraph agent state schema.

    Contains the prompt, structured specification, pre-flight feasibility report,
    planned sequence of operations, step-by-step observations, self-correction
    reflection tracking, and final execution summary.
    """
    prompt: str
    spec: Dict[str, Any]
    feasibility: Dict[str, Any]
    plan: Dict[str, Any]
    observations: List[Dict[str, Any]]
    reflection: Dict[str, Any]
    final_output: Dict[str, Any]
    status: str  # "specifying", "checking", "planning", "executing", "reflecting", "completed", "failed"
    error: Optional[str]


def create_initial_cad_state(prompt: str = "") -> CADState:
    """Initializes an empty, valid CADState dictionary."""
    return {
        "prompt": prompt,
        "spec": {},
        "feasibility": FeasibilityReport().to_dict(),
        "plan": {"steps": []},
        "observations": [],
        "reflection": ReflectionState().to_dict(),
        "final_output": {},
        "status": "specifying",
        "error": None
    }
